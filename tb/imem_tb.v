`timescale 1ns / 1ps

module imem_tb;

    //==========================================================//
    // Parameters
    //==========================================================//

    parameter DATA_WIDTH = 32;
    parameter NUM_INS    = 1000;

    //==========================================================//
    // Inputs
    //==========================================================//

    reg         clk_i;
    reg         rst_ni;
    reg         en_i;
    reg [31:0]  addr_i;

    //==========================================================//
    // Outputs
    //==========================================================//

    wire [31:0] imem_o;

    //==========================================================//
    // DUT
    //==========================================================//

    imem #(
        .DATA_WIDTH(DATA_WIDTH),
        .NUM_INS(NUM_INS)
    ) uut (
        .clk_i (clk_i),
        .en_i  (en_i),
        .addr_i(addr_i),
        .rst_ni(rst_ni),
        .imem_o(imem_o)
    );

    //==========================================================//
    // Clock Generation
    //==========================================================//

    always #5 clk_i = ~clk_i;

    //==========================================================//
    // Test Sequence
    //==========================================================//

    initial begin

        // Initialize
        clk_i  = 0;
        rst_ni = 0;
        en_i   = 0;
        addr_i = 32'd0;

        ////////////////////////////////////////////////////////
        // Reset
        ////////////////////////////////////////////////////////

        #12;
        rst_ni = 1;
        en_i   = 1;

        ////////////////////////////////////////////////////////
        // Read instruction at address 0
        ////////////////////////////////////////////////////////

        @(negedge clk_i);
        addr_i = 32'd0;

        @(posedge clk_i);
        #1;
        $display("ADDR = %d | INSTR = %h", addr_i, imem_o);

        ////////////////////////////////////////////////////////
        // Read instruction at address 4
        ////////////////////////////////////////////////////////

        @(negedge clk_i);
        addr_i = 32'd4;

        @(posedge clk_i);
        #1;
        $display("ADDR = %d | INSTR = %h", addr_i, imem_o);

        ////////////////////////////////////////////////////////
        // Read instruction at address 8
        ////////////////////////////////////////////////////////

        @(negedge clk_i);
        addr_i = 32'd8;

        @(posedge clk_i);
        #1;
        $display("ADDR = %d | INSTR = %h", addr_i, imem_o);

        ////////////////////////////////////////////////////////
        // Read instruction at address 12
        ////////////////////////////////////////////////////////

        @(negedge clk_i);
        addr_i = 32'd12;

        @(posedge clk_i);
        #1;
        $display("ADDR = %d | INSTR = %h", addr_i, imem_o);

        ////////////////////////////////////////////////////////
        // Finish
        ////////////////////////////////////////////////////////

        #10;
        $finish;

    end

endmodule