`timescale 1ns / 1ps

module dmem_tb;

    //==========================================================//
    // Parameters
    //==========================================================//
    
    parameter DATA_WIDTH = 32;
    parameter NUM_WORDS  = 32;

    //==========================================================//
    // Inputs
    //==========================================================//

    reg                  clk_i;
    reg                  en_i;
    reg  [3:0]           we_i;
    reg  [31:0]          addr_i;
    reg  [31:0]          data_i;

    //==========================================================//
    // Outputs
    //==========================================================//

    wire [31:0] mem_o;

    //==========================================================//
    // DUT
    //==========================================================//

    dmem #(
        .DATA_WIDTH(DATA_WIDTH),
        .NUM_WORDS(NUM_WORDS)
    ) uut (
        .clk_i (clk_i),
        .en_i  (en_i),
        .we_i  (we_i),
        .addr_i(addr_i),
        .data_i(data_i),
        .mem_o (mem_o)
    );

    //==========================================================//
    // Clock Generation
    //==========================================================//

    always #5 clk_i = ~clk_i;

    //==========================================================//
    // Test Sequence
    //==========================================================//

    initial begin

        // Initialize
        clk_i  = 0;
        en_i   = 1;
        we_i   = 4'b0000;
        addr_i = 32'd0;
        data_i = 32'd0;

        // Wait a little
        #20;

        //======================================================//
        // Test 1 : Write word to address 3
        //======================================================//

        @(negedge clk_i);
        addr_i = 32'd12;          // word index 3 (3*4)
        data_i = 32'hAAAA_BBBB;
        we_i   = 4'b1111;

        @(negedge clk_i);
        we_i = 4'b0000;

        // Read back
        @(negedge clk_i);
        addr_i = 32'd12;

        @(negedge clk_i);

        //======================================================//
        // Test 2 : Write word to address 7
        //======================================================//

        @(negedge clk_i);
        addr_i = 32'd28;          // word index 7 (7*4)
        data_i = 32'h1234_5678;
        we_i   = 4'b1111;

        @(negedge clk_i);
        we_i = 4'b0000;

        // Read back
        @(negedge clk_i);
        addr_i = 32'd28;

        @(negedge clk_i);

        //======================================================//
        // Test 3 : Byte write test
        //======================================================//

        @(negedge clk_i);
        addr_i = 32'd12;
        data_i = 32'hFFFF_00FF;
        we_i   = 4'b0001;     // write lowest byte only

        @(negedge clk_i);
        we_i = 4'b0000;

        @(negedge clk_i);

        //======================================================//
        // Finish
        //======================================================//

        #20;
        $stop;

    end

endmodule